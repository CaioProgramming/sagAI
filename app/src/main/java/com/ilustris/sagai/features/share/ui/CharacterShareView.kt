/** How long the share waits for the genre's fonts before giving up and using the default ones. */
private const val FONT_WAIT_MS = 4_000L

/** Lets the frozen, flat card draw once before it is captured. */
private const val FREEZE_SETTLE_MS = 400L

/**
 * The character share: a tilting, holographic collector card and a button that exports it as an
 * image. The share text is generated by [com.ilustris.sagai.features.share.ui.ShareSheet]; this view
 * only shows it.
 */
@Composable
fun CharacterShareView(
    content: Saga,
    character: CharacterContent,
    viewModel: SharePlayViewModel = hiltViewModel(),
) {
    val genre = remember(content) { content.genre }
    val isSaving by viewModel.isSaving.collectAsStateWithLifecycle()
    val isLoading by viewModel.isLoading.collectAsStateWithLifecycle()
    val shareText by viewModel.shareText.collectAsStateWithLifecycle()
    val savedPath by viewModel.savedFilePath.collectAsStateWithLifecycle()
    val originalImage by viewModel.originalBitmap.collectAsStateWithLifecycle()
    val segmentedImage by viewModel.segmentedBitmap.collectAsStateWithLifecycle()
    val lifecycleOwner = LocalLifecycleOwner.current
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val captureLayer = rememberGraphicsLayer()

    var frozen by remember { mutableStateOf(false) }

    // The share sheet opens only for an export started here. A leftover path from an earlier share
    // would otherwise open it the moment this view appears.
    var exportRequested by remember { mutableStateOf(false) }
    val tilt = rememberCardTilt(frozen)

    DisposableEffect(lifecycleOwner, viewModel) {
        lifecycleOwner.lifecycle.addObserver(viewModel)
        onDispose { lifecycleOwner.lifecycle.removeObserver(viewModel) }
    }

    LaunchedEffect(character.data.image) {
        viewModel.segmentImage(character.data.image)
    }

    LaunchedEffect(isSaving) {
        if (!isSaving) frozen = false
    }

    LaunchedEffect(savedPath) {
        val path = savedPath ?: return@LaunchedEffect
        if (exportRequested) {
            exportRequested = false
            launchShareActivity(path, context = context)
        }
    }

    SagAITheme(genre = genre) {
        val fontsReady = rememberGenreFontsReady(genre)

        Box(Modifier.fillMaxWidth(), contentAlignment = Alignment.Center) {
            AnimatedVisibility(isLoading.not(), enter = fadeIn() + scaleIn(), exit = fadeOut()) {
                Column(
                    Modifier.padding(16.dp),
                    horizontalAlignment = Alignment.CenterHorizontally,
                    verticalArrangement = Arrangement.spacedBy(20.dp),
                ) {
                    CollectorCard(
                        genre = genre,
                        title = "${character.data.name} ${character.data.lastName.orEmpty()}".trim(),
                        subtitle = character.data.profile.occupation,
                        number = "#${character.data.id}",
                        body = shareText?.text,
                        tilt = tilt,
                        captureLayer = captureLayer,
                        modifier = Modifier.fillMaxWidth(),
                    ) { cardTilt, scale ->
                        CharacterArt(
                            imageUrl = character.data.image,
                            original = originalImage,
                            segmented = segmentedImage,
                            genre = genre,
                            tilt = cardTilt,
                            scale = scale,
                        )
                    }

                    Button(
                        enabled = fontsReady && !frozen && !isSaving,
                        onClick = {
                            scope.launch {
                                exportRequested = true
                                frozen = true
                                delay(FREEZE_SETTLE_MS)
                                val bitmap = captureLayer.toImageBitmap().asAndroidBitmap()
                                viewModel.saveBitmap(bitmap, ShareType.CHARACTER.name)
                            }
                        },
                    ) {
                        Icon(painterResource(R.drawable.ic_share), contentDescription = null, modifier = Modifier.size(18.dp))
                        Spacer(Modifier.width(8.dp))
                        Text(stringResource(R.string.share))
                    }
                }
            }

            StarryLoader(isLoading, brushColors = genre.colorPalette())
        }
    }
}

/**
 * The art behind the card: the character cut out over their own backdrop when segmentation is done,
 * the plain portrait until then. The genre filter is baked once, not run per frame. The two layers drift in opposite directions as the card tilts.
 */
@Composable
private fun BoxScope.CharacterArt(
    imageUrl: String,
    original: Bitmap?,
    segmented: Bitmap?,
    genre: Genre,
    tilt: () -> Offset,
    scale: Float,
) {
    val density = LocalDensity.current.density

    // Both layers are scaled up so their drift never shows an edge.
    fun Modifier.drift(
        distanceDp: Float,
        zoom: Float,
    ) = graphicsLayer {
        val t = tilt()
        translationX = t.x * distanceDp * scale * density
        translationY = t.y * distanceDp * scale * density
        scaleX = zoom
        scaleY = zoom
    }

    if (original != null && segmented != null) {
        BakedGenreImage(
            bitmap = original,
            genre = genre,
            modifier = Modifier.fillMaxSize().drift(-6f, 1.1f),
            // The backdrop still contains the character. Blurred, the offset copy reads as depth of
            // field behind the sharp cut-out instead of as a second, doubled figure.
            blur = 10.dp,
        )
        BakedGenreImage(
            bitmap = segmented,
            genre = genre,
            modifier = Modifier.fillMaxSize().drift(4f, 1.05f),
        )
    } else {
        // Plain until the cut-out is ready: the genre filter is applied once, to the finished pair.
        AsyncImage(
            model = imageUrl,
            contentDescription = null,
            contentScale = ContentScale.Crop,
            modifier = Modifier.fillMaxSize().drift(-5f, 1.1f),
        )
    }
}

/**
 * True once the genre's remote fonts are resolved, or after [FONT_WAIT_MS] regardless. Exporting
 * before then would bake the default font into the picture.
 */
@Composable
private fun rememberGenreFontsReady(genre: Genre): Boolean {
    val services = rememberGenreThemeServices()
    val fonts = services?.fontService?.fontsFor(genre)?.collectAsStateWithLifecycle()?.value
    var waited by remember { mutableStateOf(false) }
    LaunchedEffect(genre) {
        delay(FONT_WAIT_MS)
        waited = true
    }
    return fonts != null || waited || services == null
}
