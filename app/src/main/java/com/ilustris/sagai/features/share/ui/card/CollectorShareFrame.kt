/** How long the share waits for the genre's fonts before giving up and using the default ones. */
private const val FONT_WAIT_MS = 4_000L

/** Lets the frozen, flat card draw once before it is captured. */
private const val FREEZE_SETTLE_MS = 400L

/** Room around the card in the video, so the 3D rotation never clips at its corners. */
private val VIDEO_MARGIN = 12.dp

/**
 * Everything the collector shares have in common: the genre theme, the loading state, the tilt, the
 * Share button, and the export of the card as an image. The share text is generated by
 * [com.ilustris.sagai.features.share.ui.ShareSheet]; this only shows it.
 *
 * The share sheet opens only after the button is pressed, from a flat capture of the card, so a path
 * left over from an earlier share can never open it on its own.
 *
 * @param card draws the card. It receives the tilt, the layer it must record itself into
 * (see [recordTo]), and the generated text, which is null if generation failed.
 */
@Composable
fun CollectorShareFrame(
    // Null for a share that belongs to the player: it wears the app's own colours.
    genre: Genre?,
    exportName: String,
    viewModel: SharePlayViewModel,
    card: @Composable (tilt: CardTiltState, captureLayer: GraphicsLayer, shareText: ShareText?) -> Unit,
) {
    val isSaving by viewModel.isSaving.collectAsStateWithLifecycle()
    val isLoading by viewModel.isLoading.collectAsStateWithLifecycle()
    val shareText by viewModel.shareText.collectAsStateWithLifecycle()
    val savedPath by viewModel.savedFilePath.collectAsStateWithLifecycle()
    val lifecycleOwner = LocalLifecycleOwner.current
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val captureLayer = rememberGraphicsLayer()
    // Records the card with its 3D rotation, for the video; the flat capture above is for the image.
    val videoLayer = rememberGraphicsLayer()

    var frozen by remember { mutableStateOf(false) }
    var exportRequested by remember { mutableStateOf(false) }
    var videoProgress by remember { mutableStateOf<Float?>(null) }
    val rendering = videoProgress != null
    val tilt = rememberCardTilt(frozen)

    DisposableEffect(lifecycleOwner, viewModel) {
        lifecycleOwner.lifecycle.addObserver(viewModel)
        onDispose { lifecycleOwner.lifecycle.removeObserver(viewModel) }
    }

    LaunchedEffect(isSaving) {
        if (!isSaving) frozen = false
    }

    LaunchedEffect(savedPath) {
        val path = savedPath ?: return@LaunchedEffect
        if (exportRequested) {
            exportRequested = false
            launchShareActivity(path, context = context)
        }
    }

    SagAITheme(genre = genre) {
        val fontsReady = rememberGenreFontsReady(genre)

        Box(Modifier.fillMaxWidth(), contentAlignment = Alignment.Center) {
            AnimatedVisibility(isLoading.not(), enter = fadeIn() + scaleIn(), exit = fadeOut()) {
                Column(
                    Modifier.padding(16.dp),
                    horizontalAlignment = Alignment.CenterHorizontally,
                    verticalArrangement = Arrangement.spacedBy(20.dp),
                ) {
                    Box(Modifier.fillMaxWidth().recordTo(videoLayer).padding(VIDEO_MARGIN)) {
                        card(tilt, captureLayer, shareText)
                    }

                    val ready = fontsReady && !frozen && !isSaving && !rendering
                    Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                        Button(
                            enabled = ready,
                            onClick = {
                                scope.launch {
                                    exportRequested = true
                                    frozen = true
                                    delay(FREEZE_SETTLE_MS)
                                    val bitmap = captureLayer.toImageBitmap().asAndroidBitmap()
                                    viewModel.saveBitmap(bitmap, exportName)
                                }
                            },
                        ) {
                            Icon(painterResource(R.drawable.ic_share), contentDescription = null, modifier = Modifier.size(18.dp))
                            Spacer(Modifier.width(8.dp))
                            Text(stringResource(R.string.share))
                        }

                        OutlinedButton(
                            enabled = ready,
                            onClick = {
                                scope.launch {
                                    val file = viewModel.newVideoFile(exportName) ?: return@launch
                                    videoProgress = 0f
                                    val rendered =
                                        runCatching { renderCardVideo(videoLayer, tilt, file) { videoProgress = it } }
                                            .onFailure { Timber.e(it, "Could not render the card video") }
                                            .isSuccess
                                    videoProgress = null
                                    val uri = if (rendered) viewModel.shareUriFor(file) else null
                                    if (uri != null) launchShareActivity(uri, context, mimeType = "video/mp4") else file.delete()
                                }
                            },
                        ) {
                            Text(videoProgress?.let { "${(it * 100).toInt()}%" } ?: stringResource(R.string.share_video))
                        }
                    }
                }
            }

            StarryLoader(isLoading, brushColors = genre?.colorPalette() ?: iridescentGradient)
        }
    }
}

/** Records the content into [layer] and draws it from there, so the card can be exported as an image. */
fun Modifier.recordTo(layer: GraphicsLayer): Modifier =
    drawWithContent {
        layer.record { this@drawWithContent.drawContent() }
        drawLayer(layer)
    }

/** Slides a layer with the tilt, scaled up so the drift never shows an edge. */
fun Modifier.drift(
    tilt: () -> Offset,
    distanceDp: Float,
    zoom: Float,
    scale: Float,
): Modifier =
    graphicsLayer {
        val t = tilt()
        translationX = t.x * distanceDp * scale * density
        translationY = t.y * distanceDp * scale * density
        scaleX = zoom
        scaleY = zoom
    }

/**
 * True once the genre's remote fonts are resolved, or after [FONT_WAIT_MS] regardless. Exporting
 * before then would bake the default font into the picture.
 */
@Composable
private fun rememberGenreFontsReady(genre: Genre?): Boolean {
    val services = rememberGenreThemeServices()
    val fonts = genre?.let { services?.fontService?.fontsFor(it)?.collectAsStateWithLifecycle()?.value }
    var waited by remember { mutableStateOf(false) }
    LaunchedEffect(genre) {
        delay(FONT_WAIT_MS)
        waited = true
    }
    return genre == null || fonts != null || waited || services == null
}
